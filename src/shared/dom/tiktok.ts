import type { RelockrSettings } from "@/types/RelockrSettings";
import { rlog } from "../rlog";
import { SettingsKey } from "../settings/settingsKey";
import { hideElement } from "./domUtils";
import { isHiddenSettingOn } from "./utils/hiddenSetting";

/**
 * TikTok cleanup with no UI: dismisses the app-install prompt that blocks the
 * page. Hidden setting, on by default.
 */
export function applyTikTokModifications(
  settings: RelockrSettings,
  node: Element,
): void {
  if (isHiddenSettingOn(settings, SettingsKey.TikTok.DismissOpenAppModal)) {
    dismissOpenAppModal(node);
  }
}

// MARK: - "Get the full app experience" modal
// See htmlExamples/tiktokBlockModal.html. Anchored on data-e2e attributes
// rather than the autogenerated class names.

// The "Open TikTok" CTA is what distinguishes the app-upsell modal from the
// real login modal, which shares the `#login-modal` container and close button.
const APP_CTA_CONFIRM = '[data-e2e="middle-cta-confirm-btn"]';
// "Not now". Seen as `alt-middle-cta-cancel-btn`; suffix match also covers the
// non-alt variant.
const APP_CTA_CANCEL = '[data-e2e$="middle-cta-cancel-btn"]';
const MODAL_CLOSE = '[data-e2e="modal-close-inner-button"]';

// Modals we've already pressed dismiss on. If one is still present on a later
// pass, TikTok ignored the click and we hide it instead of clicking forever.
const dismissAttempted = new WeakSet<Element>();
const DISMISS_RECHECK_MS = 1500;

function dismissOpenAppModal(node: Element): void {
  const confirmBtn = node.querySelector(APP_CTA_CONFIRM);
  if (!confirmBtn) return;

  const modal =
    confirmBtn.closest("#login-modal") ??
    confirmBtn.closest('[data-e2e="middle-cta-container"]');
  if (!modal) return;

  if (!dismissAttempted.has(modal)) {
    // Prefer TikTok's own dismiss so it tears down its focus lock and scroll
    // lock itself.
    const dismissBtn =
      modal.querySelector<HTMLElement>(APP_CTA_CANCEL) ??
      modal.querySelector<HTMLElement>(MODAL_CLOSE);
    if (dismissBtn) {
      dismissAttempted.add(modal);
      rlog("TikTok: dismissing open-app modal");
      dismissBtn.click();
      // If TikTok ignores the click, this check hides the modal instead.
      window.setTimeout(
        () => dismissOpenAppModal(document.documentElement),
        DISMISS_RECHECK_MS,
      );
      return;
    }
  }

  // The focus-lock wrapper holds the modal and its backdrop-side focus guards.
  const root = modal.closest("[data-focus-lock-disabled]") ?? modal;
  if ((root as HTMLElement).dataset?.hideReason) return;
  rlog("TikTok: open-app modal survived dismiss; hiding it");
  hideElement(root, "TikTok open-app modal");
  restoreScrolling();
}

/** TikTok locks page scroll while its modal is up; undo it when we hide one. */
function restoreScrolling(): void {
  for (const el of [document.documentElement, document.body]) {
    if (!el) continue;
    el.style.overflow = "";
    el.style.position = "";
    el.style.top = "";
    el.style.width = "";
  }
}
